create table if not exists public.profiles (
  id integer primary key default 1 check (id = 1),
  full_name text not null default 'Your Name',
  role text default 'Musician · Artist',
  bio text default '',
  about text default '',
  avatar_url text default '',
  public_email text default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.social_links (
  id bigint generated by default as identity primary key,
  platform text not null,
  url text not null,
  is_public boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.private_details (
  id integer primary key default 1 check (id = 1),
  phone text default '',
  email text default '',
  other text default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.access_requests (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  message text default '',
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

insert into public.profiles (id) values (1) on conflict (id) do nothing;
insert into public.private_details (id) values (1) on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.social_links enable row level security;
alter table public.private_details enable row level security;
alter table public.access_requests enable row level security;
alter table public.app_admins enable row level security;

-- Helper checks use the current user's own admin row.
create or replace function public.is_site_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (select 1 from public.app_admins where user_id = auth.uid());
$$;

create policy "Public can read profile" on public.profiles
for select to anon, authenticated using (true);
create policy "Admin can manage profile" on public.profiles
for all to authenticated using (public.is_site_admin()) with check (public.is_site_admin());

create policy "Public can read public social links" on public.social_links
for select to anon, authenticated using (is_public = true);
create policy "Admin can manage social links" on public.social_links
for all to authenticated using (public.is_site_admin()) with check (public.is_site_admin());

create policy "Approved users and admin can read private details" on public.private_details
for select to authenticated using (
  public.is_site_admin() or exists (
    select 1 from public.access_requests r
    where r.user_id = auth.uid() and r.status = 'approved'
  )
);
create policy "Admin can manage private details" on public.private_details
for all to authenticated using (public.is_site_admin()) with check (public.is_site_admin());

create policy "Users can read own request; admin can read all" on public.access_requests
for select to authenticated using (auth.uid() = user_id or public.is_site_admin());
create policy "Users can create own request" on public.access_requests
for insert to authenticated with check (auth.uid() = user_id and email = auth.jwt()->>'email');
create policy "Users can update own request message while pending" on public.access_requests
for update to authenticated using (auth.uid() = user_id and status = 'pending')
with check (auth.uid() = user_id and status = 'pending');
create policy "Admin can update requests" on public.access_requests
for update to authenticated using (public.is_site_admin()) with check (public.is_site_admin());

create policy "Users can check own admin status" on public.app_admins
for select to authenticated using (auth.uid() = user_id);

